#!/usr/bin/env node
/**
 * Audit and maintain a Project Context Manifest v1 without third-party packages.
 */

import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";

const MANIFEST = ".agents/context-manifest.json";
const INDEX = "docs/CONTEXT.md";
const ADR_STATUSES = new Set(["Proposed", "Accepted", "Deprecated", "Superseded"]);
const UI_STATUSES = new Set(["Proposed", "Approved", "Implemented", "Superseded"]);
const KINDS = new Set([
  "instruction",
  "skill",
  "adr",
  "ui",
  "requirement",
  "plan",
  "handoff",
  "validation",
  "runbook",
  "other",
]);
const ACTIVE_EXCLUSIONS = new Set(["Deprecated", "Superseded", "Archived", "Historical"]);

function git(root, args, check = true) {
  const result = spawnSync("git", ["-C", root, ...args], {
    encoding: "utf8",
  });
  const output = {
    status: result.status ?? 1,
    stdout: result.stdout ?? "",
    stderr: result.stderr ?? "",
  };
  if (check && output.status !== 0) {
    throw new Error(output.stderr.trim() || output.stdout.trim() || "git failed");
  }
  return output;
}

function rootPath() {
  return resolve(git(process.cwd(), ["rev-parse", "--show-toplevel"]).stdout.trim());
}

function loadManifest(root) {
  const manifestPath = join(root, MANIFEST);
  if (!existsSync(manifestPath)) {
    throw new Error(`missing ${MANIFEST}`);
  }
  try {
    const value = JSON.parse(readFileSync(manifestPath, "utf8"));
    if (!value || Array.isArray(value) || typeof value !== "object") {
      throw new Error(`${MANIFEST} must contain a JSON object`);
    }
    return value;
  } catch (error) {
    if (error instanceof SyntaxError) {
      throw new Error(`invalid JSON in ${MANIFEST}: ${error.message}`);
    }
    throw error;
  }
}

function safePath(root, raw) {
  if (typeof raw !== "string" || !raw || isAbsolute(raw)) {
    return null;
  }
  const normalized = raw.replaceAll("\\", "/");
  if (normalized.split("/").includes("..")) {
    return null;
  }
  const candidate = resolve(root, normalized);
  if (candidate !== root && !candidate.startsWith(`${root}${sep}`)) {
    return null;
  }
  return candidate;
}

function digest(filePath) {
  return `sha256:${createHash("sha256").update(readFileSync(filePath)).digest("hex")}`;
}

function escapeTable(value) {
  return String(value ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");
}

function renderIndex(manifest, adapter) {
  const project = manifest.project && typeof manifest.project === "object" ? manifest.project : {};
  const name = typeof project.name === "string" && project.name ? project.name : "Project";
  const lines = [
    `# ${name} Context`,
    "",
    "> Generated from `.agents/context-manifest.json`. Do not edit this file by hand.",
    "",
    "## Authority Domains",
    "",
    "| Domain | Purpose | Sources |",
    "|---|---|---|",
  ];

  const domains =
    manifest.authorityDomains &&
    !Array.isArray(manifest.authorityDomains) &&
    typeof manifest.authorityDomains === "object"
      ? manifest.authorityDomains
      : {};
  for (const key of Object.keys(domains).sort()) {
    const data = domains[key] && typeof domains[key] === "object" ? domains[key] : {};
    const sourceText = Array.isArray(data.sources) ? data.sources.map(String).join(" → ") : "";
    lines.push(
      `| ${escapeTable(key)} | ${escapeTable(data.description)} | ${escapeTable(sourceText)} |`,
    );
  }

  lines.push(
    "",
    "## Repository Scopes",
    "",
    "| Scope | Instructions | Skills |",
    "|---|---|---|",
  );
  const scopes = Array.isArray(manifest.scopes)
    ? manifest.scopes
        .filter((item) => item && !Array.isArray(item) && typeof item === "object")
        .sort((left, right) => String(left.path ?? "").localeCompare(String(right.path ?? "")))
    : [];
  for (const scope of scopes) {
    const skills = Array.isArray(scope.skills) ? scope.skills.map(String).join(", ") : "";
    lines.push(
      `| \`${escapeTable(scope.path)}\` | \`${escapeTable(scope.agents)}\` | ${escapeTable(skills)} |`,
    );
  }

  lines.push(
    "",
    "## Context Artifacts",
    "",
    "| ID | Kind | Status | Title | Path | Owners |",
    "|---|---|---|---|---|---|",
  );
  const artifacts = Array.isArray(manifest.artifacts)
    ? manifest.artifacts
        .filter((item) => item && !Array.isArray(item) && typeof item === "object")
        .sort(
          (left, right) =>
            String(left.kind ?? "").localeCompare(String(right.kind ?? "")) ||
            String(left.id ?? "").localeCompare(String(right.id ?? "")),
        )
    : [];
  for (const item of artifacts) {
    const owners = Array.isArray(item.owners) ? item.owners.map(String).join(", ") : "";
    lines.push(
      `| \`${escapeTable(item.id)}\` | ${escapeTable(item.kind)} | ${escapeTable(item.status)} | ` +
        `${escapeTable(item.title)} | \`${escapeTable(item.path)}\` | ${escapeTable(owners)} |`,
    );
  }

  lines.push("", "## Context Commands", "");
  if (adapter === "node") {
    lines.push(
      "```bash",
      "node .agents/scripts/context-audit.mjs check",
      "node .agents/scripts/context-audit.mjs index",
      "node .agents/scripts/context-audit.mjs acknowledge <artifact-id>",
      "```",
    );
  } else if (adapter === "python") {
    lines.push(
      "```bash",
      "python3 .agents/scripts/context_audit.py check",
      "python3 .agents/scripts/context_audit.py index",
      "python3 .agents/scripts/context_audit.py acknowledge <artifact-id>",
      "```",
    );
  } else {
    lines.push("No supported repo-native audit adapter is installed; follow the manual audit contract.");
  }
  lines.push("");
  return lines.join("\n");
}

function installedAdapter(root) {
  if (existsSync(join(root, ".agents/scripts/context-audit.mjs"))) {
    return "node";
  }
  if (existsSync(join(root, ".agents/scripts/context_audit.py"))) {
    return "python";
  }
  return "manual";
}

function walkFiles(root) {
  if (!existsSync(root)) {
    return [];
  }
  const files = [];
  const pending = [root];
  while (pending.length) {
    const current = pending.pop();
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const fullPath = join(current, entry.name);
      if (entry.isDirectory()) {
        pending.push(fullPath);
      } else if (entry.isFile()) {
        files.push(fullPath);
      }
    }
  }
  return files;
}

function collectOrphans(root, registered) {
  const candidates = [];
  const adrDir = join(root, "docs/adr");
  if (existsSync(adrDir)) {
    for (const entry of readdirSync(adrDir, { withFileTypes: true })) {
      if (entry.isFile() && entry.name.endsWith(".md") && entry.name !== "TEMPLATE.md") {
        candidates.push(join(adrDir, entry.name));
      }
    }
  }
  const uiDir = join(root, "docs/ui");
  for (const filePath of walkFiles(uiDir)) {
    const name = filePath.split(sep).at(-1);
    if (name !== "TEMPLATE.md" && (filePath.endsWith(".md") || filePath.endsWith(".html"))) {
      candidates.push(filePath);
    }
  }
  const skillsDir = join(root, ".agents/skills");
  if (existsSync(skillsDir)) {
    for (const entry of readdirSync(skillsDir, { withFileTypes: true })) {
      const skill = join(skillsDir, entry.name, "SKILL.md");
      if (entry.isDirectory() && existsSync(skill)) {
        candidates.push(skill);
      }
    }
  }
  return candidates
    .map((filePath) => relative(root, filePath).split(sep).join("/"))
    .filter((filePath) => !registered.has(filePath))
    .sort();
}

function validate(root, manifest) {
  const errors = [];
  const warnings = [];
  if (manifest.$schema !== "./context-manifest.schema.json") {
    errors.push("$schema must equal './context-manifest.schema.json'");
  }
  if (!existsSync(join(root, ".agents/context-manifest.schema.json"))) {
    errors.push("missing .agents/context-manifest.schema.json");
  }
  if (manifest.schemaVersion !== 1) {
    errors.push("schemaVersion must equal 1");
  }
  if (
    !manifest.project ||
    typeof manifest.project !== "object" ||
    typeof manifest.project.name !== "string" ||
    !manifest.project.name
  ) {
    errors.push("project.name must be a non-empty string");
  }
  if (!manifest.project || typeof manifest.project !== "object" || manifest.project.root !== ".") {
    errors.push("project.root must equal '.'");
  }

  let domains = {};
  if (
    !manifest.authorityDomains ||
    Array.isArray(manifest.authorityDomains) ||
    typeof manifest.authorityDomains !== "object" ||
    Object.keys(manifest.authorityDomains).length === 0
  ) {
    errors.push("authorityDomains must be a non-empty object");
  } else {
    domains = manifest.authorityDomains;
    for (const [key, value] of Object.entries(domains)) {
      if (!value || typeof value !== "object" || typeof value.description !== "string") {
        errors.push(`authority domain ${JSON.stringify(key)} needs a description`);
      }
      if (!value || typeof value !== "object" || !Array.isArray(value.sources) || !value.sources.length) {
        errors.push(`authority domain ${JSON.stringify(key)} needs at least one source`);
      }
    }
  }

  if (!Array.isArray(manifest.scopes) || !manifest.scopes.length) {
    errors.push("scopes must be a non-empty array");
  } else {
    manifest.scopes.forEach((scope, position) => {
      if (!scope || Array.isArray(scope) || typeof scope !== "object") {
        errors.push(`scope ${position} must be an object`);
        return;
      }
      for (const key of ["path", "agents", "skills"]) {
        if (!(key in scope)) {
          errors.push(`scope ${position} is missing ${key}`);
        }
      }
      const scopePath = safePath(root, scope.path);
      const agentsPath = safePath(root, scope.agents);
      if (!scopePath || !existsSync(scopePath) || !statSync(scopePath).isDirectory()) {
        errors.push(`scope ${position} has an invalid or missing path`);
      }
      if (!agentsPath || !existsSync(agentsPath) || !statSync(agentsPath).isFile()) {
        errors.push(`scope ${position} has an invalid or missing AGENTS.md`);
      }
      if (!Array.isArray(scope.skills)) {
        errors.push(`scope ${position} skills must be an array`);
      } else {
        for (const skill of scope.skills) {
          if (typeof skill !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(skill)) {
            errors.push(`scope ${position} has an invalid skill name ${JSON.stringify(skill)}`);
          } else if (!existsSync(join(root, ".agents/skills", skill, "SKILL.md"))) {
            errors.push(`scope ${position} references missing skill ${JSON.stringify(skill)}`);
          }
        }
      }
    });
  }

  if (!Array.isArray(manifest.artifacts)) {
    errors.push("artifacts must be an array");
    return { errors, warnings };
  }

  const ids = new Map();
  const registered = new Set();
  const supersedes = new Map();
  manifest.artifacts.forEach((artifact, position) => {
    if (!artifact || Array.isArray(artifact) || typeof artifact !== "object") {
      errors.push(`artifact ${position} must be an object`);
      return;
    }
    const artifactId = artifact.id;
    if (typeof artifactId !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(artifactId)) {
      errors.push(`artifact ${position} has an invalid id`);
      return;
    }
    if (ids.has(artifactId)) {
      errors.push(`duplicate artifact id: ${artifactId}`);
    }
    ids.set(artifactId, artifact);

    if (!KINDS.has(artifact.kind)) {
      errors.push(`${artifactId}: unsupported kind ${JSON.stringify(artifact.kind)}`);
    }
    if (typeof artifact.title !== "string" || !artifact.title) {
      errors.push(`${artifactId}: title must be a non-empty string`);
    }
    if (typeof artifact.status !== "string" || !artifact.status) {
      errors.push(`${artifactId}: status must be a non-empty string`);
    }
    if (artifact.kind === "adr" && !ADR_STATUSES.has(artifact.status)) {
      errors.push(`${artifactId}: invalid ADR status ${JSON.stringify(artifact.status)}`);
    }
    if (artifact.kind === "ui" && !UI_STATUSES.has(artifact.status)) {
      errors.push(`${artifactId}: invalid UI status ${JSON.stringify(artifact.status)}`);
    }

    const filePath = safePath(root, artifact.path);
    if (!filePath) {
      errors.push(`${artifactId}: path must be a safe repository-relative path`);
    } else {
      registered.add(String(artifact.path).replaceAll("\\", "/"));
      if (!existsSync(filePath) || !statSync(filePath).isFile()) {
        errors.push(`${artifactId}: missing file ${artifact.path}`);
      } else {
        const mustDigest =
          (artifact.kind === "adr" && artifact.status === "Accepted") ||
          (artifact.kind === "ui" &&
            (artifact.status === "Approved" || artifact.status === "Implemented"));
        if (mustDigest && typeof artifact.contentDigest !== "string") {
          errors.push(`${artifactId}: status ${artifact.status} requires contentDigest`);
        }
        if (typeof artifact.contentDigest === "string" && artifact.contentDigest !== digest(filePath)) {
          errors.push(`${artifactId}: contentDigest does not match ${artifact.path}`);
        }
      }
    }

    if (!Array.isArray(artifact.authorityDomains)) {
      errors.push(`${artifactId}: authorityDomains must be an array`);
    } else {
      for (const domain of artifact.authorityDomains) {
        if (!(domain in domains)) {
          errors.push(`${artifactId}: unknown authority domain ${JSON.stringify(domain)}`);
        }
      }
    }

    for (const field of ["owners", "appliesTo", "relationships", "implementationRefs"]) {
      if (!Array.isArray(artifact[field])) {
        errors.push(`${artifactId}: ${field} must be an array`);
      }
    }
    if (
      artifact.kind === "ui" &&
      artifact.status === "Implemented" &&
      (!Array.isArray(artifact.implementationRefs) || !artifact.implementationRefs.length)
    ) {
      errors.push(`${artifactId}: Implemented UI evidence requires implementationRefs`);
    }

    if (Array.isArray(artifact.relationships)) {
      for (const relationship of artifact.relationships) {
        if (!relationship || Array.isArray(relationship) || typeof relationship !== "object") {
          errors.push(`${artifactId}: relationship must be an object`);
          continue;
        }
        if (typeof relationship.target !== "string" || typeof relationship.type !== "string") {
          errors.push(`${artifactId}: relationship needs type and target`);
        }
        if (relationship.type === "supersedes" && typeof relationship.target === "string") {
          const targets = supersedes.get(artifactId) ?? [];
          targets.push(relationship.target);
          supersedes.set(artifactId, targets);
        }
      }
    }

    if (!artifact.review || Array.isArray(artifact.review) || typeof artifact.review !== "object") {
      errors.push(`${artifactId}: review must be an object`);
    } else {
      for (const reviewField of ["commit", "at", "by"]) {
        if (!(reviewField in artifact.review)) {
          errors.push(`${artifactId}: review is missing ${reviewField}`);
        }
      }
      const commit = artifact.review.commit;
      for (const reviewField of ["at", "by"]) {
        if (
          artifact.review[reviewField] !== null &&
          artifact.review[reviewField] !== undefined &&
          typeof artifact.review[reviewField] !== "string"
        ) {
          errors.push(`${artifactId}: review.${reviewField} must be a string or null`);
        }
      }
      if (commit === null || commit === undefined) {
        warnings.push(`${artifactId}: has no reviewed commit`);
      } else if (typeof commit !== "string") {
        errors.push(`${artifactId}: review.commit must be a string or null`);
      } else if (git(root, ["cat-file", "-e", `${commit}^{commit}`], false).status !== 0) {
        warnings.push(`${artifactId}: reviewed commit ${commit} is unavailable`);
      } else if (git(root, ["merge-base", "--is-ancestor", commit, "HEAD"], false).status !== 0) {
        warnings.push(`${artifactId}: reviewed commit ${commit} is not an ancestor of HEAD`);
      } else if (Array.isArray(artifact.appliesTo) && artifact.appliesTo.length) {
        const diff = git(root, ["diff", "--name-only", `${commit}..HEAD`, "--", ...artifact.appliesTo], false);
        if (diff.status !== 0) {
          warnings.push(`${artifactId}: affected-path comparison failed`);
        } else if (diff.stdout.trim()) {
          const changed = diff.stdout.trim().split("\n").slice(0, 5).join(", ");
          warnings.push(`${artifactId}: review required after changes to ${changed}`);
        }
      }
      if (Array.isArray(artifact.appliesTo) && artifact.appliesTo.length) {
        const dirty = git(root, ["status", "--porcelain", "--", ...artifact.appliesTo], false);
        if (dirty.status !== 0) {
          warnings.push(`${artifactId}: uncommitted affected-path comparison failed`);
        } else if (dirty.stdout.trim()) {
          const changed = dirty.stdout
            .split("\n")
            .filter(Boolean)
            .slice(0, 5)
            .map((line) => (line.length > 3 ? line.slice(3) : line))
            .join(", ");
          warnings.push(`${artifactId}: uncommitted affected changes require review: ${changed}`);
        }
      }
    }
  });

  for (const [artifactId, artifact] of ids) {
    if (!Array.isArray(artifact.relationships)) {
      continue;
    }
    for (const relationship of artifact.relationships) {
      if (!relationship || Array.isArray(relationship) || typeof relationship !== "object") {
        continue;
      }
      if (typeof relationship.target === "string" && !ids.has(relationship.target)) {
        errors.push(`${artifactId}: relationship target ${JSON.stringify(relationship.target)} does not exist`);
      }
      if (relationship.type === "supersedes" && ids.has(relationship.target)) {
        const reciprocal = ids.get(relationship.target).relationships;
        const valid =
          Array.isArray(reciprocal) &&
          reciprocal.some(
            (item) =>
              item &&
              !Array.isArray(item) &&
              typeof item === "object" &&
              item.type === "superseded-by" &&
              item.target === artifactId,
          );
        if (!valid) {
          errors.push(
            `${artifactId}: supersedes ${relationship.target} without reciprocal superseded-by`,
          );
        }
      }
    }
  }

  const visiting = new Set();
  const visited = new Set();
  function visit(artifactId) {
    if (visiting.has(artifactId)) {
      errors.push(`supersession cycle includes ${artifactId}`);
      return;
    }
    if (visited.has(artifactId)) {
      return;
    }
    visiting.add(artifactId);
    for (const target of supersedes.get(artifactId) ?? []) {
      if (ids.has(target)) {
        visit(target);
      }
    }
    visiting.delete(artifactId);
    visited.add(artifactId);
  }
  for (const artifactId of supersedes.keys()) {
    visit(artifactId);
  }

  const active = [...ids.values()].filter(
    (artifact) =>
      !ACTIVE_EXCLUSIONS.has(artifact.status) &&
      Array.isArray(artifact.authorityDomains) &&
      Array.isArray(artifact.appliesTo),
  );
  active.forEach((left, index) => {
    for (const right of active.slice(index + 1)) {
      const domainsOverlap = left.authorityDomains.some((item) => right.authorityDomains.includes(item));
      const sharedPaths = left.appliesTo.filter((item) => right.appliesTo.includes(item));
      if (domainsOverlap && sharedPaths.length) {
        warnings.push(
          `${left.id} and ${right.id}: overlapping active authority for ${[...new Set(sharedPaths)]
            .sort()
            .join(", ")}`,
        );
      }
    }
  });

  for (const orphan of collectOrphans(root, registered)) {
    warnings.push(`unregistered context artifact: ${orphan}`);
  }

  const expectedIndex = renderIndex(manifest, installedAdapter(root));
  const indexPath = join(root, INDEX);
  if (!existsSync(indexPath)) {
    errors.push(`missing generated index ${INDEX}; run index`);
  } else if (readFileSync(indexPath, "utf8") !== expectedIndex) {
    errors.push(`generated index ${INDEX} is stale; run index`);
  }
  return { errors, warnings };
}

function writeIndex(root, manifest) {
  const indexPath = join(root, INDEX);
  mkdirSync(dirname(indexPath), { recursive: true });
  writeFileSync(indexPath, renderIndex(manifest, installedAdapter(root)), "utf8");
  console.log(`wrote ${INDEX}`);
}

function acknowledge(root, manifest, artifactId) {
  const artifacts = Array.isArray(manifest.artifacts) ? manifest.artifacts : [];
  const artifact = artifacts.find((item) => item && typeof item === "object" && item.id === artifactId);
  if (!artifact) {
    throw new Error(`unknown artifact id: ${artifactId}`);
  }
  let paths = Array.isArray(artifact.appliesTo) && artifact.appliesTo.length
    ? artifact.appliesTo
    : [artifact.path];
  paths = paths.filter((item) => typeof item === "string" && item);
  const status = git(root, ["status", "--porcelain", "--", ...paths]);
  if (status.stdout.trim()) {
    throw new Error("cannot acknowledge while affected paths have uncommitted changes");
  }
  const reviewer = git(root, ["config", "user.name"], false).stdout.trim();
  if (!reviewer) {
    throw new Error("git config user.name is required for acknowledgement");
  }
  const commit = git(root, ["rev-parse", "HEAD"]).stdout.trim();
  const reviewedAt = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
  artifact.review = { commit, at: reviewedAt, by: reviewer };
  writeFileSync(join(root, MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  writeIndex(root, manifest);
  console.log(`acknowledged ${artifactId} at ${commit}`);
}

function main() {
  const command = process.argv[2] ?? "check";
  try {
    const root = rootPath();
    const manifest = loadManifest(root);
    if (command === "index") {
      writeIndex(root, manifest);
      return 0;
    }
    if (command === "acknowledge") {
      if (process.argv.length !== 4) {
        throw new Error("usage: context-audit.mjs acknowledge <artifact-id>");
      }
      acknowledge(root, manifest, process.argv[3]);
      return 0;
    }
    if (command !== "check") {
      throw new Error("command must be check, index, or acknowledge");
    }
    const { errors, warnings } = validate(root, manifest);
    errors.forEach((error) => console.log(`ERROR ${error}`));
    warnings.forEach((warning) => console.log(`WARNING ${warning}`));
    if (errors.length) {
      console.log(
        `context audit failed with ${errors.length} error(s) and ${warnings.length} warning(s)`,
      );
      return 1;
    }
    console.log(`context audit passed with ${warnings.length} warning(s)`);
    return 0;
  } catch (error) {
    console.error(`ERROR ${error instanceof Error ? error.message : String(error)}`);
    return 2;
  }
}

process.exitCode = main();
