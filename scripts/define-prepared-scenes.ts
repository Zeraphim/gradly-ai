// Dev-only, billed. Never import this from server.ts or apps/. It runs the
// production Scene Designer stage (designScenes) and the Research Methods
// Reviewer (reviewLesson) from the API on each prepared study, for challenges
// without an authored scene, then saves the results to
// apps/web/src/research/studies/data/scenes/<slug>.ts. Prepared studies read
// those files and never call the model at runtime. Authored scenes,
// questions, answers, excerpts and terms are left as they are.
//
//   npm run define:scenes                          every study without a scenes file
//   npm run define:scenes -- --slugs a,b --force   only these, replacing their files
//   npm run define:scenes -- --fill                redraft only evidence scenes, keeping the rest
//   npm run define:scenes -- report                print saved scenes for review
//   npm run define:scenes -- prune                 apply reviewed removals to saved files
//   npm run define:scenes -- coverage              print scene coverage per study
//   npm run define:scenes -- settle                reapply the stage's repairs to saved scenes
// Options: --concurrency 3
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { pathToFileURL } from "node:url";
import { format } from "prettier";
import type { Scene } from "@paperquest/contracts";
import type { Challenge, Lesson } from "../apps/api/src/research/contracts.js";
import { reviewLesson } from "../apps/api/src/research/pipeline.js";
import { NebiusProvider } from "../apps/api/src/research/provider.js";
import {
  designScenes,
  evidenceScene,
  isEvidenceScene,
  settleScene,
  setupText,
  stageSceneProblems,
} from "../apps/api/src/research/scene-stage.js";
import { nebiusConfig } from "../apps/api/src/nebius-config.js";
import { studyCards } from "../apps/web/src/research/studies/cards.js";
import type { SavedScene } from "../apps/web/src/research/studies/catalog.js";
import type { StudyBody } from "../apps/web/src/research/studies/types.js";
import { isRemovedScene } from "./prepared-scene-review.js";

const ROOT = process.cwd();
const DATA = join(ROOT, "apps/web/src/research/studies/data");
const OUT = join(DATA, "scenes");

const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: {
    slugs: { type: "string" },
    force: { type: "boolean", default: false },
    fill: { type: "boolean", default: false },
    concurrency: { type: "string", default: "3" },
  },
});

async function body(slug: string): Promise<StudyBody> {
  return (await import(pathToFileURL(join(DATA, `${slug}.ts`)).href)).body;
}

async function savedScenes(slug: string): Promise<Record<string, SavedScene>> {
  const file = join(OUT, `${slug}.ts`);
  if (!existsSync(file)) return {};
  return (await import(`${pathToFileURL(file).href}?t=${Date.now()}`)).scenes;
}

const challengesOf = (l: Lesson | StudyBody["lesson"]) => [
  ...l.challenges,
  ...(l.bonus ? [l.bonus] : []),
];

/** Prepared studies have no stored pages; reviewers read their excerpts. */
function evidencePages(lesson: Lesson) {
  const pages = [...new Set(lesson.evidence.map((r) => r.page))];
  return pages.map((page) => ({
    page,
    text: lesson.evidence
      .filter((r) => r.page === page)
      .map((r) => r.excerpt)
      .join("\n"),
  }));
}

async function render(scenes: Record<string, SavedScene>) {
  return format(
    `// Generated by scripts/define-prepared-scenes.ts with the production Scene
// Designer stage and Research Methods Reviewer. Rerun the script instead of
// editing. Challenges with an authored scene are not listed.
import type { SavedScene } from "../../catalog.js";

export const scenes: Record<string, SavedScene> = ${JSON.stringify(scenes, null, 2)};
`,
    { parser: "typescript" },
  );
}

/** The evidence scene in place of a scene that failed review. */
function replaced(c: Challenge, lesson: Lesson): SavedScene | null {
  const scene = evidenceScene(c, lesson.evidence);
  return scene ? { scene } : null;
}

async function define(slug: string, model: string, fill = false) {
  const started = Date.now();
  const lesson = (await body(slug)).lesson as Lesson;
  // Filling keeps every saved scene except an evidence scene the stage
  // stood in with; a scene replaced after review stays replaced.
  const previous = fill ? await savedScenes(slug) : {};
  const keep = (id: string) =>
    !!previous[id] &&
    (!isEvidenceScene(previous[id]!.scene) || isRemovedScene(slug, id));
  for (const c of challengesOf(lesson))
    if (!c.scene && keep(c.id)) Object.assign(c, previous[c.id]);
  const provider = new NebiusProvider();
  // No route limit here, so each challenge gets more drafts before the
  // evidence scene stands in.
  const designed = await designScenes(lesson, provider, model, {
    keepExisting: true,
    attempts: 3,
    budgetMs: 900_000,
    callMs: 110_000,
  });
  const review = await reviewLesson(
    "methods",
    designed.lesson,
    evidencePages(lesson),
    provider,
    model,
  ).catch((e) => {
    console.warn(
      `${slug}: review unavailable: ${e instanceof Error ? e.message : e}`,
    );
    return null;
  });
  const rejected = new Set(
    (review?.rejectedScenes ?? []).map((r) => r.challenge),
  );
  const scenes: Record<string, SavedScene> = Object.fromEntries(
    Object.entries(previous).filter(([id]) => keep(id)),
  );
  let reviewerReplaced = 0;
  for (const c of challengesOf(designed.lesson)) {
    const outcome = designed.outcomes[c.id];
    if (outcome === "kept" || outcome === "plain" || !c.scene) continue;
    let saved: SavedScene | null = {
      scene: c.scene as Scene,
      ...(c.responseStyle ? { responseStyle: c.responseStyle } : {}),
    };
    if (
      !isEvidenceScene(c.scene) &&
      (rejected.has(c.id) || isRemovedScene(slug, c.id))
    ) {
      if (rejected.has(c.id)) reviewerReplaced++;
      saved = replaced(c, lesson);
    }
    if (!saved) continue;
    const problems = stageSceneProblems(
      c,
      saved.scene as Scene,
      lesson.evidence,
    );
    if (problems.length) throw Error(problems.join(" "));
    scenes[c.id] = saved;
  }
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, `${slug}.ts`), await render(scenes));
  const notes = Object.entries(designed.problems)
    .map(([id, p]) => `${id}: ${p.join(" ").slice(0, 160)}`)
    .join(" | ");
  console.log(
    `${slug}: ${designed.written - reviewerReplaced} written, ${designed.fallback + reviewerReplaced} evidence, ${designed.plain} plain, ${designed.kept} kept, ${designed.retried} redrafted, leak check replaced ${designed.leaks}, reviewer replaced ${reviewerReplaced} in ${Math.round((Date.now() - started) / 1000)}s${notes ? ` | ${notes}` : ""}`,
  );
}

/** Saved scenes beside their challenge's accepted answers, design stage first. */
async function report(slugs: string[], stage?: string) {
  for (const slug of slugs) {
    const lesson = (await body(slug)).lesson;
    const scenes = await savedScenes(slug);
    for (const c of challengesOf(lesson)) {
      const saved = scenes[c.id];
      if (!saved || (stage && c.reveal !== stage)) continue;
      const accepted = c.options
        .filter((o) => c.accepted.includes(o.id))
        .map((o) => o.text)
        .join(" | ");
      console.log(
        `\n## ${slug} ${c.id} [${c.reveal}] ${saved.scene.kind}${isEvidenceScene(saved.scene) ? " (evidence)" : ""}${saved.responseStyle ? ` ${saved.responseStyle}` : ""}\nQ: ${c.prompt}\nA: ${accepted}`,
      );
      if (isEvidenceScene(saved.scene)) continue;
      for (const line of setupText(saved.scene, c as Challenge))
        console.log(`- ${line}`);
    }
  }
}

/** Share of challenges with a scene, authored and saved together. */
async function coverage(slugs: string[]) {
  let total = 0;
  let scened = 0;
  let written = 0;
  let evidence = 0;
  for (const slug of slugs) {
    const lesson = (await body(slug)).lesson;
    const scenes = await savedScenes(slug);
    const all = challengesOf(lesson);
    const own = all.filter((c) => c.scene).length;
    const added = all.filter((c) => !c.scene && scenes[c.id]);
    const fallback = added.filter((c) => isEvidenceScene(scenes[c.id]!.scene));
    total += all.length;
    scened += own + added.length;
    written += added.length - fallback.length;
    evidence += fallback.length;
    console.log(
      `${slug}: ${own + added.length}/${all.length} (${own} authored, ${added.length - fallback.length} written, ${fallback.length} evidence)`,
    );
  }
  console.log(
    `\nAll: ${scened}/${total} challenges have a scene (${Math.round((100 * scened) / total)}%); added ${written} written and ${evidence} evidence scenes.`,
  );
}

/** Applies the reviewed removals to saved files without calling the model. */
async function prune(slugs: string[]) {
  for (const slug of slugs) {
    if (!existsSync(join(OUT, `${slug}.ts`))) continue;
    const lesson = (await body(slug)).lesson as Lesson;
    const scenes = await savedScenes(slug);
    let changed = 0;
    for (const c of challengesOf(lesson)) {
      const saved = scenes[c.id];
      if (!saved || isEvidenceScene(saved.scene) || !isRemovedScene(slug, c.id))
        continue;
      const next = replaced(c, lesson);
      if (next) scenes[c.id] = next;
      else delete scenes[c.id];
      changed++;
    }
    if (changed) {
      writeFileSync(join(OUT, `${slug}.ts`), await render(scenes));
      console.log(`${slug}: replaced ${changed} reviewed scene(s)`);
    }
  }
}

/** Reapplies the stage's model-free repairs, so saved scenes follow later fixes. */
async function settle(slugs: string[]) {
  for (const slug of slugs) {
    if (!existsSync(join(OUT, `${slug}.ts`))) continue;
    const lesson = (await body(slug)).lesson as Lesson;
    const scenes = await savedScenes(slug);
    const next: Record<string, SavedScene> = {};
    for (const c of challengesOf(lesson)) {
      const saved = scenes[c.id];
      if (!saved) continue;
      const settled = isEvidenceScene(saved.scene)
        ? saved
        : settleScene(
            c as Challenge,
            saved.scene as Scene,
            saved.responseStyle ?? "cards",
          );
      const problems = stageSceneProblems(
        c as Challenge,
        settled.scene as Scene,
        lesson.evidence,
      );
      // Listed for review; prune replaces them once they are recorded.
      if (problems.length) {
        console.error(`${slug}: ${problems.join(" ")}`);
        process.exitCode = 1;
      }
      next[c.id] = settled as SavedScene;
    }
    const before = JSON.stringify(scenes);
    if (JSON.stringify(next) !== before) {
      writeFileSync(join(OUT, `${slug}.ts`), await render(next));
      console.log(`${slug}: settled`);
    }
  }
}

const all = studyCards.map((card) => card.slug);
const chosen = values.slugs
  ? values.slugs.split(",").map((s) => s.trim())
  : all;
const unknown = chosen.filter((s) => !all.includes(s));
if (unknown.length) throw Error(`Unknown study: ${unknown.join(", ")}`);

if (positionals[0] === "report") await report(chosen, positionals[1]);
else if (positionals[0] === "prune") await prune(chosen);
else if (positionals[0] === "coverage") await coverage(chosen);
else if (positionals[0] === "settle") await settle(chosen);
else {
  if (!process.env.NEBIUS_API_KEY) throw Error("NEBIUS_API_KEY is not set.");
  const model = nebiusConfig().pipelineModelId;
  const queue = chosen.filter(
    (slug) =>
      values.force || values.fill || !existsSync(join(OUT, `${slug}.ts`)),
  );
  console.log(`Designing scenes for ${queue.length} studies with ${model}.`);
  const failed: string[] = [];
  const worker = async () => {
    for (let slug = queue.shift(); slug; slug = queue.shift())
      try {
        await define(slug, model, values.fill);
      } catch (e) {
        failed.push(slug);
        console.error(`${slug}: failed: ${e instanceof Error ? e.message : e}`);
      }
  };
  await Promise.all(Array.from({ length: Number(values.concurrency) }, worker));
  if (failed.length) {
    console.error(`Failed: ${failed.join(",")}. Rerun to retry them.`);
    process.exitCode = 1;
  }
}
