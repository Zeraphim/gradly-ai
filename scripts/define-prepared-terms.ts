// Dev-only, billed. Never import this from server.ts or apps/. It runs the
// production terms stage (draftTerms) and the Research Methods Reviewer
// (reviewLesson) from pipeline.ts on each prepared study, then saves the
// approved definitions to apps/web/src/research/studies/data/terms/<slug>.ts.
// Prepared studies read those files and never call the model at runtime.
//
//   npm run define:terms                          every study without a terms file
//   npm run define:terms -- --slugs a,b --force   only these, replacing their files
//   npm run define:terms -- report                print design-stage terms for review
//   npm run define:terms -- prune                 drop reviewed removals from saved files
// Options: --concurrency 3
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { format } from "prettier";
import { pathToFileURL } from "node:url";
import { termProblems, type Term } from "@paperquest/contracts";
import type { Lesson } from "../apps/api/src/research/contracts.js";
import { draftTerms, reviewLesson } from "../apps/api/src/research/pipeline.js";
import { NebiusProvider } from "../apps/api/src/research/provider.js";
import { isRemoved } from "./prepared-term-review.js";
import { nebiusConfig } from "../apps/api/src/nebius-config.js";
import { studyCards } from "../apps/web/src/research/studies/cards.js";
import type { StudyBody } from "../apps/web/src/research/studies/types.js";

const ROOT = process.cwd();
const DATA = join(ROOT, "apps/web/src/research/studies/data");
const OUT = join(DATA, "terms");

const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: {
    slugs: { type: "string" },
    force: { type: "boolean", default: false },
    concurrency: { type: "string", default: "3" },
  },
});

async function body(slug: string): Promise<StudyBody> {
  return (await import(pathToFileURL(join(DATA, `${slug}.ts`)).href)).body;
}

async function savedTerms(slug: string): Promise<Record<string, Term[]>> {
  const file = join(OUT, `${slug}.ts`);
  if (!existsSync(file)) return {};
  return (await import(pathToFileURL(file).href)).terms;
}

/** Prepared studies have no stored pages; reviewers read their excerpts. */
function evidencePages(lesson: Lesson) {
  const pages = [...new Set(lesson.evidence.map((r) => r.page))];
  return pages.map((page) => ({
    page,
    text: lesson.evidence
      .filter((r) => r.page === page)
      .map((r) => r.excerpt)
      .join("\n"),
  }));
}

async function render(slug: string, terms: Record<string, Term[]>) {
  return format(
    `// Generated by scripts/define-prepared-terms.ts with the production terms
// stage and Research Methods Reviewer. Rerun the script instead of editing.
import type { Term } from "@paperquest/contracts";

export const terms: Record<string, Term[]> = ${JSON.stringify(terms, null, 2)};
`,
    { parser: "typescript" },
  );
}

async function define(slug: string, model: string) {
  const started = Date.now();
  const lesson = (await body(slug)).lesson as Lesson;
  const provider = new NebiusProvider();
  // The model occasionally answers with no entries at all; ask again.
  let drafted = await draftTerms(lesson, provider, model);
  for (let retry = 0; retry < 2 && !drafted.defined; retry++)
    drafted = await draftTerms(lesson, provider, model);
  const review = await reviewLesson(
    "methods",
    drafted.lesson,
    evidencePages(lesson),
    provider,
    model,
  );
  const ids = lesson.evidence.map((r) => r.id);
  const terms: Record<string, Term[]> = {};
  for (const c of [
    ...review.lesson.challenges,
    ...(review.lesson.bonus ? [review.lesson.bonus] : []),
  ]) {
    const kept = (c.terms ?? []).filter((t) => !isRemoved(slug, c.id, t.term));
    if (!kept.length) continue;
    const problems = termProblems({ ...c, terms: kept }, ids);
    if (problems.length) throw Error(problems.join(" "));
    terms[c.id] = kept;
  }
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, `${slug}.ts`), await render(slug, terms));
  const kept = Object.values(terms).flat().length;
  console.log(
    `${slug}: kept ${kept} of ${drafted.defined + drafted.removed} proposed (checks removed ${drafted.removed}, reviewer removed ${review.removed}) in ${Math.round((Date.now() - started) / 1000)}s`,
  );
}

/** Design-stage definitions beside their challenge's accepted answers. */
async function report(slugs: string[]) {
  for (const slug of slugs) {
    const lesson = (await body(slug)).lesson;
    const terms = await savedTerms(slug);
    for (const c of [
      ...lesson.challenges,
      ...(lesson.bonus ? [lesson.bonus] : []),
    ]) {
      if (c.reveal !== "design" || !terms[c.id]) continue;
      const accepted = c.options
        .filter((o) => c.accepted.includes(o.id))
        .map((o) => o.text)
        .join(" | ");
      console.log(`\n## ${slug} ${c.id}\nQ: ${c.prompt}\nA: ${accepted}`);
      for (const t of terms[c.id]!)
        console.log(
          `- ${t.term} [${t.source}${t.refs.length ? ` ${t.refs.join(",")}` : ""}]: ${t.definition}`,
        );
    }
  }
}

const all = studyCards.map((card) => card.slug);
const chosen = values.slugs
  ? values.slugs.split(",").map((s) => s.trim())
  : all;
const unknown = chosen.filter((s) => !all.includes(s));
if (unknown.length) throw Error(`Unknown study: ${unknown.join(", ")}`);

/** Applies the reviewed removals to saved files without calling the model. */
async function prune(slugs: string[]) {
  for (const slug of slugs) {
    if (!existsSync(join(OUT, `${slug}.ts`))) continue;
    const saved = await savedTerms(slug);
    const terms: Record<string, Term[]> = {};
    let removed = 0;
    for (const [id, list] of Object.entries(saved)) {
      const kept = list.filter((t) => !isRemoved(slug, id, t.term));
      removed += list.length - kept.length;
      if (kept.length) terms[id] = kept;
    }
    if (removed) {
      writeFileSync(join(OUT, `${slug}.ts`), await render(slug, terms));
      console.log(`${slug}: removed ${removed} reviewed definition(s)`);
    }
  }
}

if (positionals[0] === "report") await report(chosen);
else if (positionals[0] === "prune") await prune(chosen);
else {
  if (!process.env.NEBIUS_API_KEY) throw Error("NEBIUS_API_KEY is not set.");
  const model = nebiusConfig().pipelineModelId;
  const queue = chosen.filter(
    (slug) => values.force || !existsSync(join(OUT, `${slug}.ts`)),
  );
  console.log(`Defining terms for ${queue.length} studies with ${model}.`);
  const failed: string[] = [];
  const worker = async () => {
    for (let slug = queue.shift(); slug; slug = queue.shift())
      try {
        await define(slug, model);
      } catch (e) {
        failed.push(slug);
        console.error(`${slug}: failed: ${e instanceof Error ? e.message : e}`);
      }
  };
  await Promise.all(Array.from({ length: Number(values.concurrency) }, worker));
  if (failed.length) {
    console.error(`Failed: ${failed.join(",")}. Rerun to retry them.`);
    process.exitCode = 1;
  }
}
